// Builds src/styles/tokens.css from design-system/tokens.json (W3C DTCG).
//   npm run tokens          write the CSS
//   npm run tokens -- --check   fail if the committed CSS is out of date (CI)
//
// Naming: a token's path joined with "-" is its CSS variable
// (color.bg.canvas -> --color-bg-canvas). Two groups are special:
//   accent.<family>.<step>        -> --accent-<step>, scoped by [data-accent]
//   destination.<name>.<path>     -> --<path>, scoped by [data-destination]
// References like {color.ink.50} become var(--color-ink-50).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'design-system', 'tokens.json');
const OUT = join(ROOT, 'src', 'styles', 'tokens.css');
const DEFAULT_ACCENT = 'viola';
const DEFAULT_DESTINATION = 'app';

const tokens = JSON.parse(readFileSync(SRC, 'utf8'));

function leaves(node, path = []) {
  if (node && typeof node === 'object' && '$value' in node) return [[path, node]];
  return Object.entries(node)
    .filter(([key]) => !key.startsWith('$'))
    .flatMap(([key, child]) => leaves(child, [...path, key]));
}

function cssValue({ $type, $value }) {
  if (typeof $value === 'string') {
    return $value.replace(/\{([^}]+)\}/g, (_, ref) => `var(--${ref.split('.').join('-')})`);
  }
  if ($type === 'cubicBezier') return `cubic-bezier(${$value.join(', ')})`;
  return String($value);
}

function block(selector, entries, comment) {
  const lines = entries.map(([name, token]) => `  --${name}: ${cssValue(token)};`);
  return `${comment ? `/* ${comment} */\n` : ''}${selector} {\n${lines.join('\n')}\n}\n`;
}

const { accent, destination, ...base } = tokens;
const parts = [
  '/* Generated by scripts/build-tokens.mjs from design-system/tokens.json. Do not edit. */\n',
  block(':root', leaves(base).map(([p, t]) => [p.join('-'), t]), 'Primitives and global scales'),
];

for (const family of Object.keys(accent).filter((k) => !k.startsWith('$'))) {
  const selector = family === DEFAULT_ACCENT ? `:root,\n[data-accent="${family}"]` : `[data-accent="${family}"]`;
  parts.push(block(selector, leaves(accent[family]).map(([p, t]) => [`accent-${p.join('-')}`, t]), `Accento: ${family}`));
}

// data-accent and data-destination go on the same element: semantic values
// are resolved where they are declared, so each scope re-declares them.
for (const name of Object.keys(destination).filter((k) => !k.startsWith('$'))) {
  const selector = name === DEFAULT_DESTINATION ? `:root,\n[data-destination="${name}"]` : `[data-destination="${name}"]`;
  const d = destination[name];
  parts.push(block(selector, leaves(d).map(([p, t]) => [p.join('-'), t]), `Destinazione: ${name}. ${d.$description ?? ''}`.trim()));
}

const css = parts.join('\n');

if (process.argv.includes('--check')) {
  if (readFileSync(OUT, 'utf8') !== css) {
    console.error('src/styles/tokens.css is out of date: run npm run tokens');
    process.exit(1);
  }
  console.log('✓ tokens.css is up to date');
} else {
  writeFileSync(OUT, css);
  console.log(`✓ wrote ${OUT.replace(`${ROOT}/`, '')}`);
}
